"""E10: multi-channel and context-conditional twin-C2ST.

Pair i has a within-date difference vector d_i (real minus synthetic; p channels, standardised by
the training-fold SD) and an unsigned context z_i (co-substrate, days in the current regime, OLR).
Features phi_i = [d_i, d_i (x) z_i] are odd in d, so a sign-equivariant linear classifier
reduces to a ridge-LDA direction w = (C + lam I)^-1 mean(phi_train). Each pair gets a cross-fitted
score u_i = w_(-week(i)) . phi_i (leave-one-week-out). The twin AUC is the expected C2ST AUC over
random sign labels, AUC = mean_{i != j} 1[u_i + u_j > 0]; its null is generated by flipping the
signs of d (phi is linear in d).

Real data: gas set (biogas, CH4, CO2), liquid set (pH, conductivity), and context-conditional
versions. Simulation (real pair dates, weeks and contexts; residual covariance of the gas set):
  S0 null; S1 diffuse shift over all gas channels; S2 co-substrate sign flip on CH4
  (+ ethanol, - whey); S3 effect that changes with days in regime (adaptation) on CH4.
Comparators: Wilcoxon on CH4; Bonferroni min-p over per-channel Wilcoxon; paired Hotelling T2
(sign-flip null); co-substrate-stratified sign-flip chi-square; unconditional twin-C2ST.
The estimator lives in twinc2st.py. Options: --sim-only, --resume, --n-sim, --n-perm, --deltas.
"""
from pathlib import Path

import argparse

import numpy as np
import pandas as pd
from scipy import stats

from twinc2st import twin_test as _twin_test

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results"
D = pd.read_csv(ROOT / "data_derived" / "features_e2.csv", parse_dates=["date"])
S = D[D.phase == "semicontinuous"].copy()
T0 = S.date.min()
ap = argparse.ArgumentParser()
ap.add_argument("--sim-only", action="store_true", help="skip the real-data block")
ap.add_argument("--resume", action="store_true", help="keep scenario settings already saved")
ap.add_argument("--n-sim", type=int, default=200)
ap.add_argument("--n-perm", type=int, default=99)
ap.add_argument("--deltas", type=float, nargs="*", default=[0.5, 1.0])
ARGS = ap.parse_args()
rng = np.random.default_rng(23)
N_PERM = ARGS.n_perm


def paired_frame(cols):
    p = S.pivot_table(index="date", columns="reactor", values=cols)
    ok = np.ones(len(p), bool)
    for c in cols:
        ok &= p[(c, "R1")].notna().values & p[(c, "R2")].notna().values
    p = p[ok]
    d = np.column_stack([(p[(c, "R2")] - p[(c, "R1")]).values for c in cols])
    ctx = S[S.reactor == "R1"].set_index("date").loc[p.index]
    z = np.column_stack([(ctx.co_type == "Etanol").astype(float), (ctx.co_type == "Suero").astype(float),
                         (ctx.days_in_regime - ctx.days_in_regime.mean()) / ctx.days_in_regime.std(),
                         (ctx.olr - ctx.olr.mean()) / (ctx.olr.std() + 1e-9)])
    wk = ((p.index - T0).days // 7).values
    return d, z, wk, ctx.co_type.values


def twin_test(d, z, wk, cond, rng):
    return _twin_test(d, z, wk, cond, rng, n_perm=N_PERM)


def hotelling_p(d, rng):
    def t2(x):
        m = x.mean(0)
        C = np.cov(x, rowvar=False).reshape(x.shape[1], x.shape[1]) + 1e-9 * np.eye(x.shape[1])
        return len(x) * m @ np.linalg.solve(C, m)
    obs = t2(d)
    null = [t2(d * rng.choice([-1, 1], len(d))[:, None]) for _ in range(N_PERM)]
    return (np.sum(np.array(null) >= obs) + 1) / (N_PERM + 1)


def strat_chi2_p(x, co, rng):
    def stat(v):
        return sum(len(v[co == k]) * v[co == k].mean() ** 2 for k in np.unique(co)) / (v.var() + 1e-12)
    obs = stat(x)
    null = [stat(x * rng.choice([-1, 1], len(x))) for _ in range(N_PERM)]
    return (np.sum(np.array(null) >= obs) + 1) / (N_PERM + 1)


# ---------------- real data ----------------
SETS = {"gas (biogas, CH4, CO2)": ["biogas", "ch4", "co2"], "CH4 only": ["ch4"], "methane volume": ["biogas"],
        "liquid (pH, conductivity)": ["ph", "cond"]}
rows = []
for name, cols in ({} if ARGS.sim_only else SETS).items():
    if name == "methane volume":
        S["meth"] = S.biogas * S.ch4 / 100
        cols = ["meth"]
    d, z, wk, co = paired_frame(cols)
    for cond in [False, True]:
        auc, p = twin_test(d, z, wk, cond, rng)
        rows.append(dict(channel_set=name, conditional=cond, n_pairs=len(d), twin_auc=auc, p_value=p))
        print(rows[-1], flush=True)
    rows[-1]["p_hotelling"] = hotelling_p(d, rng)
    rows[-1]["p_strat_chi2_first_channel"] = strat_chi2_p(d[:, 0], co, rng)
if rows:
    R = pd.DataFrame(rows)
    R.to_csv(OUT / "E10_real_multichannel_conditional.csv", index=False)
    print(R.round(3).to_string())

# ---------------- simulation ----------------
GAS = ["biogas", "ch4", "co2"]
d0, z0, wk0, co0 = paired_frame(GAS)
Sig = np.cov(d0 - d0.mean(0), rowvar=False)
sd0 = np.sqrt(np.diag(Sig))
L = np.linalg.cholesky(Sig)
dir_sign = np.array([1, 1, -1])  # diffuse shift direction (more gas, more CH4, less CO2)
SCEN = {
    "S0 null": lambda dl: np.zeros_like(d0),
    "S1 diffuse shift": lambda dl: np.tile(dl / np.sqrt(3) * sd0 * dir_sign, (len(d0), 1)),
    "S2 co-substrate sign flip": lambda dl: np.outer(dl * ((co0 == "Etanol").astype(float) - (co0 == "Suero").astype(float)),
                                                    np.array([0, sd0[1], 0])),
    "S3 adaptation-dependent": lambda dl: np.outer(dl * z0[:, 2], np.array([0, sd0[1], 0])),
}
f10 = OUT / "E10_simulation.csv"
rows = pd.read_csv(f10).to_dict("records") if ARGS.resume and f10.exists() else []
done = {(r["scenario"], float(r["delta_sd"])) for r in rows}
for sc, f in SCEN.items():
    for dl in ([0.0] if sc == "S0 null" else ARGS.deltas):
        if (sc, dl) in done:
            continue
        res = []
        for _ in range(ARGS.n_sim):
            d = f(dl) + rng.standard_normal(d0.shape) @ L.T
            r = dict(
                wilcoxon_ch4=stats.wilcoxon(d[:, 1]).pvalue,
                bonf_wilcoxon=min(1, 3 * min(stats.wilcoxon(d[:, k]).pvalue for k in range(3))),
                hotelling=hotelling_p(d, rng),
                strat_chi2_ch4=strat_chi2_p(d[:, 1], co0, rng),
                twin_c2st=twin_test(d, z0, wk0, False, rng)[1],
                twin_c2st_conditional=twin_test(d, z0, wk0, True, rng)[1],
            )
            res.append(r)
        res = pd.DataFrame(res)
        row = dict(scenario=sc, delta_sd=dl, n_sim=len(res), n_perm=N_PERM,
                   **{f"reject_{k}": (res[k] < 0.05).mean() for k in res})
        rows.append(row)
        print(row, flush=True)
        pd.DataFrame(rows).to_csv(f10, index=False)
print(pd.DataFrame(rows).round(3).to_string())
