"""Twin classifier two-sample test (twin-C2ST) for paired, schedule-matched reactors.

Pair i has a within-date difference vector d_i (real minus synthetic; standardised by the
training-fold SD) and an unsigned context z_i. Features phi_i = [d_i, d_i (x) z_i] are odd in d,
so a sign-equivariant linear classifier of the random-sign samples (s_i phi_i, s_i) reduces to a
ridge-LDA direction w = (C + lam I)^-1 mean(phi_train). Each pair receives a cross-fitted score
u_i = w_(-week(i)) . phi_i (leave-one-week-out). The twin AUC is the expected C2ST AUC over random
sign labels, AUC = mean_{i != j} {1[u_i + u_j > 0] + 0.5 * 1[u_i + u_j = 0]};
its null is generated by flipping the signs
of d (phi is linear in d), which keeps every pair's date, schedule and context fixed.
"""
from __future__ import annotations

import numpy as np


def features(d, z, cond):
    return np.hstack([d] + [d * z[:, [k]] for k in range(z.shape[1])]) if cond else d


def cross_scores(d, z, wk, cond, lam=2.0):
    u = np.zeros(len(d))
    for w in np.unique(wk):
        te, tr = wk == w, wk != w
        sd = d[tr].std(0, ddof=1) + 1e-9
        ftr, fte = features(d[tr] / sd, z[tr], cond), features(d[te] / sd, z[te], cond)
        C = np.cov(ftr, rowvar=False, bias=True).reshape(ftr.shape[1], ftr.shape[1])
        w_ = np.linalg.solve(C + lam * np.eye(len(C)), ftr.mean(0))
        u[te] = fte @ w_
    return u


def sym_auc(u):
    s = u[:, None] + u[None, :]
    # Remove self-comparisons before comparisons turn NaN into False.
    # The denominator is n * (n - 1), as in the off-diagonal U-statistic.
    off = s[~np.eye(len(u), dtype=bool)]
    return np.mean((off > 0) + 0.5 * (off == 0))


def twin_test(d, z, wk, cond, rng, n_perm=99, return_null=False):
    obs = sym_auc(cross_scores(d, z, wk, cond))
    null = np.array([sym_auc(cross_scores(d * rng.choice([-1, 1], len(d))[:, None], z, wk, cond))
                     for _ in range(n_perm)])
    p = (np.sum(null >= obs) + 1) / (n_perm + 1)
    return (obs, p, null) if return_null else (obs, p)
